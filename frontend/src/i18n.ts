export function getLanguage(): Language {
  try {
    const saved = localStorage.getItem("farmshield-language");
    return saved === "te" || saved === "hi" ? saved : "en";
  } catch {
    return "en";
  }
}

export function getIntlLocale(): string {
  const language = document.documentElement.lang;
  return language === "te" ? localeNames.te : language === "hi" ? localeNames.hi : localeNames.en;
}

export function translate(source: string, language: Language): string {
  if (language === "en") return source;
  const dictionary = { ...dictionaries[language], ...additionalTranslations[language] };
  const trimmed = source.trim();
  const direct = dictionary[trimmed];
  if (direct) return `${source.slice(0, source.indexOf(trimmed))}${direct}${source.slice(source.indexOf(trimmed) + trimmed.length)}`;

  const deleteFacilityLabel = trimmed.match(/^Delete (.+)$/);
  if (deleteFacilityLabel) {
    const facilityName = dictionary[deleteFacilityLabel[1]] ?? deleteFacilityLabel[1];
    return language === "te" ? `${facilityName} తొలగించు` : `${facilityName} हटाएँ`;
  }
  const availabilityLabel = trimmed.match(/^(Make available|Mark unavailable): (.+)$/);
  if (availabilityLabel) {
    const facilityName = dictionary[availabilityLabel[2]] ?? availabilityLabel[2];
    const action = availabilityLabel[1] === "Make available"
      ? (language === "te" ? "అందుబాటులో ఉంచు" : "उपलब्ध करें")
      : (language === "te" ? "అందుబాటులో లేదని గుర్తించు" : "अनुपलब्ध करें");
    return `${action}: ${facilityName}`;
  }

  const rows = trimmed.match(/^Showing ([\d,–-]+) of ([\d,]+) rows$/);
  if (rows) {
    const translated = language === "te"
      ? `${rows[1]}లో ${rows[2]} వరుసలను చూపుతోంది`
      : `${rows[2]} వరుసల్లో ${rows[1]} చూపిస్తోంది`;
    return `${source.slice(0, source.indexOf(trimmed))}${translated}${source.slice(source.indexOf(trimmed) + trimmed.length)}`;
  }
  const facilities = trimmed.match(/^(\d+) sample facilities$/);
  if (facilities) return language === "te" ? `${facilities[1]} నమూనా నిల్వ కేంద్రాలు` : `${facilities[1]} नमूना भंडारण केंद्र`;
  const dayCount = trimmed.match(/^(\d+) days?$/);
  if (dayCount) return language === "te" ? `${dayCount[1]} రోజులు` : `${dayCount[1]} दिन`;
  const marketHeading = trimmed.match(/^(.+?) at (.+)\. Price per quintal\.$/);
  if (marketHeading) {
    const market = dictionary[marketHeading[2]] ?? marketHeading[2];
    return language === "te"
      ? `${marketHeading[1]} — ${market}లో ప్రతి క్వింటాల్ ధర.`
      : `${marketHeading[1]} — ${market} में हर क्विंटल का भाव।`;
  }
  const marketChange = trimmed.match(/^([+-][\d.]+%) sample change$/);
  if (marketChange) return language === "te" ? `${marketChange[1]} నమూనా మార్పు` : `${marketChange[1]} का नमूना बदलाव`;
  const sampleLocality = trimmed.match(/^(.+?) example(, .+)?$/);
  if (sampleLocality) return language === "te"
    ? `${sampleLocality[1]} నమూనా${sampleLocality[2] ?? ""}`
    : `${sampleLocality[1]} का नमूना${sampleLocality[2] ?? ""}`;
  const chartDescription = trimmed.match(/^Prices are shown in rupees per quintal for (.+?) at (.+)\. All values are sample data, not live rates\.$/);
  if (chartDescription) {
    const market = dictionary[chartDescription[2]] ?? chartDescription[2];
    return language === "te"
      ? `${chartDescription[1]} పంటకు ${market}లో క్వింటాల్‌కు రూపాయల్లో ధరలు చూపబడ్డాయి. అన్ని విలువలు నమూనా మాత్రమే; ప్రస్తుత మార్కెట్ ధరలు కావు.`
      : `${chartDescription[1]} के लिए ${market} में भाव रुपये प्रति क्विंटल में दिखाए गए हैं। सभी मान नमूना हैं, आज के बाज़ार भाव नहीं।`;
  }
  const quantitySummary = trimmed.match(/^([\d,.]+) (quintals|tonnes|kilograms) \(([\d,.]+) (quintals|tonnes|kilograms)\)$/);
  if (quantitySummary) {
    const units: Record<string, [string, string]> = {
      quintals: ["క్వింటాళ్లు", "क्विंटल"],
      tonnes: ["టన్నులు", "टन"],
      kilograms: ["కిలోగ్రాములు", "किलोग्राम"],
    };
    const unit = (value: string) => units[value][language === "te" ? 0 : 1];
    return `${quantitySummary[1]} ${unit(quantitySummary[2])} (${quantitySummary[3]} ${unit(quantitySummary[4])})`;
  }
  const quantityLoss = trimmed.match(/^([\d,.]+) (quintals|tonnes|kilograms) after ([\d,.]+)% assumed storage loss$/);
  if (quantityLoss) {
    const unit = quantityLoss[2] === "quintals" ? (language === "te" ? "క్వింటాళ్లు" : "क्विंटल") : quantityLoss[2] === "tonnes" ? (language === "te" ? "టన్నులు" : "टन") : (language === "te" ? "కిలోగ్రాములు" : "किलोग्राम");
    return language === "te"
      ? `${quantityLoss[1]} ${unit}; నిల్వలో ${quantityLoss[3]}% నష్టం ఉంటుందని అంచనా`
      : `${quantityLoss[1]} ${unit}; भंडारण में ${quantityLoss[3]}% कमी मानकर`;
  }
  const quantityUnit = trimmed.match(/^([\d,.]+) (quintals|tonnes|kilograms)$/);
  if (quantityUnit) {
    const units: Record<string, [string, string]> = {
      quintals: ["క్వింటాళ్లు", "क्विंटल"],
      tonnes: ["టన్నులు", "टन"],
      kilograms: ["కిలోగ్రాములు", "किलोग्राम"],
    };
    return `${quantityUnit[1]} ${units[quantityUnit[2]][language === "te" ? 0 : 1]}`;
  }
  const scenarioDifference = trimmed.match(/^(.+) (above|below) the sell-now estimate under these assumptions$/);
  if (scenarioDifference) {
    return language === "te"
      ? `ఈ అంచనాల ప్రకారం ఇప్పుడే అమ్మే అంచనా కంటే ${scenarioDifference[1]} ${scenarioDifference[2] === "above" ? "ఎక్కువ" : "తక్కువ"}`
      : `इन अनुमानों के अनुसार अभी बेचने की कमाई से ${scenarioDifference[1]} ${scenarioDifference[2] === "above" ? "अधिक" : "कम"}`;
  }
  const activities = trimmed.match(/^(\d+) activities$/);
  if (activities) return language === "te" ? `${activities[1]} పనులు` : `${activities[1]} काम`;
  const advisoryDays = trimmed.match(/^Daily farm advisory — next (\d+) days$/);
  if (advisoryDays) return language === "te"
    ? `రోజువారీ వ్యవసాయ సలహా — తదుపరి ${advisoryDays[1]} రోజులు`
    : `रोज़ाना खेत सलाह — अगले ${advisoryDays[1]} दिन`;
  const harvestAround = trimmed.match(/^Harvest around (.+)$/);
  if (harvestAround) return language === "te"
    ? `కోత సుమారుగా ${harvestAround[1]}`
    : `कटाई लगभग ${harvestAround[1]}`;
  const dynamic = trimmed.match(/^(.+?) added to your demo crop calendar\.$/);
  if (dynamic) return language === "te" ? `${dynamic[1]} మీ నమూనా పంట క్యాలెండర్‌కు చేర్చబడింది.` : `${dynamic[1]} आपके नमूना फसल कैलेंडर में जोड़ी गई।`;
  const dynamicCalendar = trimmed.match(/^(.+) calendar is available to review\.$/);
  if (dynamicCalendar) return language === "te" ? `${dynamicCalendar[1]} క్యాలెండర్‌ను పరిశీలించవచ్చు.` : `${dynamicCalendar[1]} का कैलेंडर देखा जा सकता है।`;
  const storageForCrop = trimmed.match(/^Storage examples for (.+)$/);
  if (storageForCrop) return language === "te" ? `${storageForCrop[1]} నిల్వ నమూనాలు` : `${storageForCrop[1]} के भंडारण नमूने`;
  const notEntered = trimmed.match(/^(\d+) sample facilities$/);
  if (notEntered) return language === "te" ? `${notEntered[1]} నమూనా కేంద్రాలు` : `${notEntered[1]} नमूना केंद्र`;
  const occupied = trimmed.match(/^Occupied capacity \((tonnes|kilograms)\) \*$/);
  if (occupied) {
    const unit = occupied[1] === "tonnes" ? (language === "te" ? "టన్నులు" : "टन") : (language === "te" ? "కిలోగ్రాములు" : "किलोग्राम");
    return language === "te" ? `నిండిన సామర్థ్యం (${unit}) *` : `भरी हुई क्षमता (${unit}) *`;
  }
  const deleteFacility = trimmed.match(/^Remove "(.+)" from the shared demo listings\? This cannot be undone\.$/);
  if (deleteFacility) {
    return language === "te"
      ? `"${deleteFacility[1]}" నిల్వ కేంద్రాన్ని నమూనా జాబితా నుంచి తొలగించాలా? దీన్ని తిరిగి మార్చలేరు.`
      : `क्या "${deleteFacility[1]}" केंद्र को नमूना सूची से हटाएँ? इसे वापस नहीं किया जा सकता।`;
  }
  const cropPlan = trimmed.match(/^(.+) is on your farm plan\.$/);
  if (cropPlan) return language === "te" ? `మీ పొలం ప్రణాళికలో ${cropPlan[1]} ఉంది.` : `आपकी खेत योजना में ${cropPlan[1]} है।`;
  const cost = trimmed.match(/^([\d,.]+) (tonnes|kilograms) × daily price × ([\d,.]+) days$/);
  if (cost) {
    const unit = cost[2] === "tonnes" ? (language === "te" ? "టన్నులు" : "टन") : (language === "te" ? "కిలోగ్రాములు" : "किलोग्राम");
    return language === "te"
      ? `${cost[1]} ${unit} × రోజువారీ ధర × ${cost[3]} రోజులు`
      : `${cost[1]} ${unit} × रोज़ का किराया × ${cost[3]} दिन`;
  }
  return translateKnownPhrases(source, language);
}

function translateTextNode(node: Text, language: Language) {
  const current = node.nodeValue ?? "";
  let record = textRecords.get(node);
  if (!record) {
    record = { source: current, output: current };
    textRecords.set(node, record);
  } else if (current !== record.output) {
    record.source = current;
  }
  const output = translate(record.source, language);
  if (output !== current) node.nodeValue = output;
  record.output = output;
}

function translateKnownPhrases(source: string, language: Exclude<Language, "en">): string {
  const dictionary = { ...dictionaries[language], ...additionalTranslations[language] };
  const entries = Object.entries(dictionary)
    .filter(([phrase, translation]) =>
      phrase.length >= 15 &&
      phrase.includes(" ") &&
      translation !== phrase &&
      /[A-Za-z]{2}/.test(phrase) &&
      !/^[A-Z0-9 .·&/-]+$/.test(phrase),
    )
    .sort(([left], [right]) => right.length - left.length);

  return entries.reduce((text, [phrase, translation]) => {
    const escaped = phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const pattern = new RegExp(`(^|[^A-Za-z])(${escaped})(?=$|[^A-Za-z])`, "g");
    return text.replace(pattern, (_match, prefix: string) => `${prefix}${translation}`);
  }, source);
}

function translateAttribute(element: Element, name: string, language: Language) {
  const current = element.getAttribute(name);
  if (current === null) return;
  let attributes = attributeRecords.get(element);
  if (!attributes) {
    attributes = new Map();
    attributeRecords.set(element, attributes);
  }
  let record = attributes.get(name);
  if (!record) {
    record = { source: current, output: current };
    attributes.set(name, record);
  } else if (current !== record.output) {
    record.source = current;
  }
  const output = translate(record.source, language);
  if (output !== current) element.setAttribute(name, output);
  record.output = output;
}

function translateTree(root: ParentNode, language: Language) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const text = node as Text;
    const element = text.parentElement;
    if (!element || element.closest("script,style,textarea")) continue;
    if (element.tagName === "OPTION" && element.parentElement && !element.hasAttribute("value")) {
      element.setAttribute("value", text.nodeValue ?? "");
    }
    translateTextNode(text, language);
  }

  if (root instanceof Element) {
    const elements = [root, ...root.querySelectorAll("*")];
    for (const element of elements) {
      for (const attribute of ["aria-label", "aria-description", "placeholder", "title", "alt"]) {
        translateAttribute(element, attribute, language);
      }
    }
  } else {
    for (const element of root.querySelectorAll("*")) {
      for (const attribute of ["aria-label", "aria-description", "placeholder", "title", "alt"]) {
        translateAttribute(element, attribute, language);
      }
    }
  }
}

export function useLocalization(language: Language) {
  useEffect(() => {
    document.documentElement.lang = language;
    const root = document.getElementById("root");
    if (!root) return;
    translateTree(root, language);
    const observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "characterData" && record.target instanceof Text) {
          translateTextNode(record.target, language);
        } else if (record.type === "childList") {
          record.addedNodes.forEach((node) => {
            if (node instanceof Text) translateTextNode(node, language);
            else if (node instanceof Element) translateTree(node, language);
          });
        } else if (record.type === "attributes" && record.target instanceof Element && record.attributeName) {
          translateAttribute(record.target, record.attributeName, language);
        }
      }
    });
    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["aria-label", "aria-description", "placeholder", "title", "alt"],
    });
    return () => observer.disconnect();
  }, [language]);
}
